"""Generate tools/subtitles/speakers.h: the speaker shown in front of each voice caption ("Raziel: ...").

The speaker of every voice id comes from the approved dialogue plans in content/. Where plans disagree the
authoritative order is: manual overrides, dialogue-text-approval.json, then the majority of the other plans.
"""
import argparse
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"
OUTPUT = ROOT / "tools" / "subtitles" / "speakers.h"
SLOTS = 479

# Display names (pt-BR) in the order the C++ table indexes them; 0 means "no speaker label".
NAMES = ["raziel", "elder", "kain", "ariel", "rahab", "melchiah", "dumah", "moebius", "zephon", "tomb_guardian"]
LABELS = {"raziel": "Raziel", "elder": "Ancião", "kain": "Kain", "ariel": "Ariel", "rahab": "Rahab",
          "melchiah": "Melchiah", "dumah": "Dumah", "moebius": "Moebius", "zephon": "Zephon",
          "tomb_guardian": "Guardião"}
# Contextual cast corrections (cast-audit-v1): the cut-story Ariel variants had a wrong Kain assignment.
OVERRIDES = {126: "ariel"}
AUTHORITATIVE = "dialogue-text-approval.json"


def collect(path):
    rows = []

    def walk(node):
        if isinstance(node, dict):
            if isinstance(node.get("id"), int) and isinstance(node.get("speaker"), str):
                rows.append((node["id"], node["speaker"]))
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(json.loads(path.read_text(encoding="utf-8-sig")))
    return rows


def resolve(content=CONTENT):
    votes = collections.defaultdict(collections.Counter)
    authoritative = {}
    for path in sorted(content.glob("*.json")):
        try:
            rows = collect(path)
        except (ValueError, OSError):
            continue
        for voice_id, speaker in rows:
            votes[voice_id][speaker] += 1
            if path.name == AUTHORITATIVE:
                authoritative[voice_id] = speaker
    result = {}
    for voice_id, counter in votes.items():
        result[voice_id] = OVERRIDES.get(voice_id) or authoritative.get(voice_id) or counter.most_common(1)[0][0]
    return result


def render(speakers):
    table = [0] * SLOTS
    for voice_id, speaker in speakers.items():
        if 0 <= voice_id < SLOTS and speaker in NAMES:
            table[voice_id] = NAMES.index(speaker) + 1
    rows = ",".join(str(value) for value in table)
    labels = ",".join(f'L"{LABELS[name]}"' for name in NAMES)
    return (
        "// Generated by tools/gen_speakers_header.py; do not edit by hand.\n"
        "#pragma once\n\n"
        f"static const unsigned char kSpeakerOfVoice[{SLOTS}] = {{{rows}}};\n"
        f"static const wchar_t* const kSpeakerLabels[] = {{L\"\",{labels}}};\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed header is stale")
    args = parser.parse_args()
    text = render(resolve())
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("speakers.h is stale; run tools/gen_speakers_header.py")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT}")
