"""Assemble a core-compatible external texture package from staged candidates.

Payloads are hard links to the existing staged RAWs (same volume required), so
the source candidates are not copied or modified. No runtime loader config is
generated by this tool.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

SOURCE_SHA256 = "f287fc2b7452aa3f2592c5bab36654ac8ed2aa1be571e607a31e29a3666868fa"
PAGE_COUNT = 1287
RAW_BYTES = 1024 * 1024 * 2
SHA256 = re.compile(r"^[0-9a-f]{64}$")


def assemble(batch: Path, output: Path) -> dict:
    batch = batch.resolve(strict=True)
    output = output.resolve()
    manifest_path = batch / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    index = json.loads((batch / "index.json").read_text(encoding="utf-8"))
    if manifest.get("schema") != 1 or manifest.get("sourceArchiveSHA256") != SOURCE_SHA256:
        raise ValueError("Manifesto do lote não corresponde à fonte suportada")
    pages = manifest.get("pages")
    if manifest.get("pagesProcessed") != PAGE_COUNT or not isinstance(pages, list) or len(pages) != PAGE_COUNT:
        raise ValueError("O lote precisa conter exatamente 1.287 páginas")
    if index.get("schema") != 1 or not isinstance(index.get("pages"), dict):
        raise ValueError("Índice do lote inválido")
    if output.exists() and any(output.iterdir()):
        raise ValueError(f"A pasta de saída não está vazia: {output}")
    manifest_out = output / "textures.json"
    if manifest_out.exists():
        raise ValueError(f"Manifesto de saída já existe: {manifest_out}")
    output.mkdir(parents=True, exist_ok=True)
    payload_dir = output / "payload"
    payload_dir.mkdir(exist_ok=True)

    assets = []
    seen = set()
    for page in sorted(pages, key=lambda item: item.get("id", -1)):
        page_id = page.get("id")
        digest = page.get("candidatePackedSHA256")
        if type(page_id) is not int or not 0 <= page_id < PAGE_COUNT or page_id in seen:
            raise ValueError(f"Página ausente, duplicada ou inválida: {page_id!r}")
        if not isinstance(digest, str) or not SHA256.fullmatch(digest):
            raise ValueError(f"SHA-256 inválido na página {page_id}")
        seen.add(page_id)
        index_entry = index["pages"].get(str(page_id))
        if not isinstance(index_entry, dict) or index_entry.get("candidatePackedSHA256") != digest:
            raise ValueError(f"Índice divergente na página {page_id}")
        relative_source = Path(index_entry.get("packedRaw", ""))
        if relative_source.is_absolute() or ".." in relative_source.parts or not relative_source.parts:
            raise ValueError(f"Caminho candidato inválido na página {page_id}")
        source = (batch / relative_source).resolve(strict=True)
        if not source.is_file() or source.stat().st_size != RAW_BYTES:
            raise ValueError(f"RAW candidato ausente ou com tamanho inesperado na página {page_id}")
        dest_name = f"page-{page_id:04}.raw"
        payload = payload_dir / dest_name
        if payload.exists():
            if not os.path.samefile(source, payload):
                raise ValueError(f"Payload preexistente não é o mesmo arquivo: {payload}")
        else:
            try:
                os.link(source, payload)
            except OSError as exc:
                raise ValueError(f"Não foi possível criar hard link para a página {page_id}; não foi feita cópia: {exc}") from exc
        assets.append({
            "file": f"hd-textures/page-{page_id:04}.raw",
            "source_sha256": None,
            "result_sha256": digest,
            "payload": f"payload/{dest_name}",
        })
    if seen != set(range(PAGE_COUNT)):
        raise ValueError("A lista de páginas não cobre 0..1286")

    package = {"schema": 1, "assets": assets}
    manifest_out.write_text(json.dumps(package, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"status": "ok", "assets": len(assets), "payloadBytes": len(assets) * RAW_BYTES,
            "payloadMode": "hard links; conteúdo da staging não copiado nem alterado",
            "manifest": str(manifest_out)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--batch", type=Path, default=Path(__file__).resolve().parents[2] / "staging/hd-textures-full-v1")
    parser.add_argument("--out", type=Path, required=True, help="Diretório do pacote externo")
    args = parser.parse_args()
    try:
        result = assemble(args.batch, args.out)
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
        print(f"Erro ao montar pacote: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
